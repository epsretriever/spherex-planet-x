#!/usr/bin/env node
// Root build used by Cloudflare Workers Builds: `npm ci && npm run build`, then `npx wrangler deploy`.
//  1. Builds the frontend static export into frontend/out (Next.js `output: "export"`).
//     If the frontend app is not in the tree yet, frontend/public (which holds the pipeline's
//     static data under data/) is copied to frontend/out so the API still has its data.
//  2. Stamps the commit into worker/src/build-info.ts when building in CI.
//  3. Type-checks the Worker.
import { execSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const frontend = join(root, "frontend");
const out = join(frontend, "out");

const run = (cmd) => {
  console.log(`$ ${cmd}`);
  execSync(cmd, { cwd: root, stdio: "inherit" });
};

function hasBuildScript(dir) {
  const pkg = join(dir, "package.json");
  if (!existsSync(pkg)) return false;
  return Boolean(JSON.parse(readFileSync(pkg, "utf8")).scripts?.build);
}

// 1. Frontend
if (hasBuildScript(frontend)) {
  run("npm run build --workspace frontend");
  if (!existsSync(join(out, "index.html"))) {
    console.error(
      "frontend build did not produce frontend/out/index.html; set output: 'export' in next.config",
    );
    process.exit(1);
  }
} else {
  console.log("frontend app not present: publishing frontend/public as frontend/out");
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  if (existsSync(join(frontend, "public"))) cpSync(join(frontend, "public"), out, { recursive: true });
  if (!existsSync(join(out, "index.html"))) {
    writeFileSync(
      join(out, "index.html"),
      `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>SPHEREx Planet X</title></head><body style="font-family:system-ui,sans-serif;max-width:40rem;margin:3rem auto;padding:0 1rem;background:#0b0e14;color:#e8ecf4"><h1>SPHEREx Planet X</h1><p>API: <a style="color:#6cb4ff" href="/api/health">/api/health</a> · <a style="color:#6cb4ff" href="/api/fields">/api/fields</a></p></body></html>\n`,
    );
  }
}

// 2. Commit stamp (CI only, so local builds leave the tree clean)
const sha = process.env.WORKERS_CI_COMMIT_SHA;
if (sha) {
  writeFileSync(
    join(root, "worker/src/build-info.ts"),
    `// Generated by scripts/build.mjs in Cloudflare Workers Builds.\nexport const BUILD_COMMIT: string = ${JSON.stringify(sha)};\n`,
  );
}

// 3. Worker type-check
run("npm run typecheck --workspace worker");
console.log("build complete");
