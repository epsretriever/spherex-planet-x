const D2R = Math.PI / 180;
/** Julian centuries from J2000.0 to B1875.0 (JD 2405889.25855). */
const T1875 = (2405889.25855 - 2451545.0) / 36525;

/** Precesses J2000 RA/Dec (degrees) to the B1875 equator and equinox. */
function precessToB1875(raDeg: number, decDeg: number): { raHours: number; decDeg: number } {
  const t = T1875;
  const as = (arcsec: number) => (arcsec / 3600) * D2R;
  const zeta = as(2306.2181 * t + 0.30188 * t * t + 0.017998 * t ** 3);
  const z = as(2306.2181 * t + 1.09468 * t * t + 0.018203 * t ** 3);
  const theta = as(2004.3109 * t - 0.42665 * t * t - 0.041833 * t ** 3);
  const a = raDeg * D2R;
  const d = decDeg * D2R;
  const A = Math.cos(d) * Math.sin(a + zeta);
  const B = Math.cos(theta) * Math.cos(d) * Math.cos(a + zeta) - Math.sin(theta) * Math.sin(d);
  const C = Math.sin(theta) * Math.cos(d) * Math.cos(a + zeta) + Math.cos(theta) * Math.sin(d);
  let ra = (Math.atan2(A, B) + z) / D2R;
  ra = ((ra % 360) + 360) % 360;
  return { raHours: ra / 15, decDeg: Math.asin(Math.max(-1, Math.min(1, C))) / D2R };
}

export interface ConstellationInfo {
  /** Three-letter IAU abbreviation, e.g. "Aqr". */
  abbr: string;
  /** Full name, e.g. "Aquarius". */
  name: string;
}

/** The constellation containing a J2000 position (RA and Dec in degrees), or null for bad input. */
export function constellationAt(raDeg: number, decDeg: number): ConstellationInfo | null {
  if (!Number.isFinite(raDeg) || !Number.isFinite(decDeg) || Math.abs(decDeg) > 90) return null;
  const p = precessToB1875(raDeg, decDeg);
  const fd = 10 / (4 * 60); // compact units → degrees of Dec
  const fr = fd / 15; // compact units → hours of RA
  for (const [i, raLo, raHi, decLo] of BOUNDS) {
    if (decLo * fd <= p.decDeg && raLo * fr <= p.raHours && p.raHours < raHi * fr) {
      const [abbr, name] = NAMES[i]!;
      return { abbr, name };
    }
  }
  return null;
}
